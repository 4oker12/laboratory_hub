'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const base=path.join(__dirname,'..');
const file=x=>fs.readFileSync(path.join(base,x),'utf8');
const flow=vm.runInNewContext(file('flow.js')+'\nC20Flow',{TextEncoder});
assert.equal(flow.classifyNative({isC20:true,stage:'FACTORY_PASSWORD'}).phase,'CREATE_ADMIN');
assert.equal(flow.classifyNative({isC20:true,stage:'LOGIN_FORM'}).phase,'LOGIN');
assert.equal(flow.classifyNative({isC20:true,stage:'QUICK_SETUP_ACTIVE'}).phase,'QUICK_SETUP');
assert.equal(flow.classifyNative({isC20:true,stage:'CONFIGURED_AUTHENTICATED'}).phase,'WIFI_EDITOR');
assert.equal(flow.classifyNative({isC20:false,stage:'QUICK_SETUP_ACTIVE'}).phase,'NO_C20');
assert.equal(flow.quickStepFromSignals({wlan:true,isp:true}), 'WIRELESS');
assert.throws(()=>flow.cleanWifi({ssid24:'one'}),/BOTH_SSIDS/);
assert.throws(()=>flow.cleanWifi({ssid24:'x'.repeat(33),ssid5:'safe'}),/SSID24/);
assert.throws(()=>flow.cleanWifi({wifiPassword:'1234567'}),/PASSWORD/);
assert.equal(flow.cleanWifi({ssid24:'A',ssid5:'B',wifiPassword:'password999'}).hasKey,true);
console.log('PASS: exactly two user modes with factory/login/quick/editor internal phases; validated Wi-Fi input');
const src=file('background.js');
assert.match(src,/case 'c20\.discoverUnified'/);assert.match(src,/case 'c20\.continueUnified'/);
assert.match(src,/if\(flow\.phase==='CREATE_ADMIN'\)/);assert.match(src,/if\(flow\.phase==='LOGIN'\)/);
assert.match(src,/if\(flow\.phase==='QUICK_SETUP'\)/);assert.match(src,/if\(flow\.phase==='WIFI_EDITOR'\)/);
assert.match(src,/await nativeSetWifi\(/);
assert.match(src,/lastProbeStage=nativeStage\(n\)/);
const ui=file('setup.js');
assert(!ui.includes('c20.probe'));assert(!ui.includes('c20.nativeRead'));assert(!ui.includes('c20.nativeLogin'));
assert(ui.includes("action(discover)"));
console.log('PASS: UI single auto-discovery path and one context-dependent primary button');
